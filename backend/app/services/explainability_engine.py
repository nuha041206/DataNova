"""
DataNova explainability engine.

Produces the "Why did DataNova produce these results?" section.

Every sentence is generated by comparing ACTUAL numbers computed by the
evaluation / ML-utility engines. There are no canned generic claims: each rule
fires only when its threshold condition is met on the real computed values.
"""
from __future__ import annotations

from typing import Any, Dict, List

import numpy as np


def _fmt(x: Any, digits: int = 3) -> str:
    """Format a number for a sentence; None-safe."""
    if x is None:
        return "n/a"
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    try:
        return f"{float(x):.{digits}f}"
    except (TypeError, ValueError):
        return str(x)


def explain_evaluation(eval_result: Dict[str, Any]) -> List[Dict[str, str]]:
    """
    Turn evaluation numbers into plain-language findings.

    Returns a list of {title, text, kind} dicts where kind is one of
    positive / neutral / warning, used by the UI to colour the cards.
    """
    findings: List[Dict[str, str]] = []
    if not eval_result:
        return findings

    score = (eval_result.get("data_nova_score") or {}).get("value")
    if score is not None:
        if score >= 0.85:
            kind, verdict = "positive", "closely matches the real data overall"
        elif score >= 0.7:
            kind, verdict = "neutral", "is broadly similar to the real data with some differences"
        else:
            kind, verdict = "warning", "differs noticeably from the real data"
        findings.append({
            "title": "Overall similarity",
            "text": f"The DataNova similarity score is {_fmt(score)} (0–1 scale), which means the synthetic data {verdict}.",
            "kind": kind,
        })

    # Per-column strongest / weakest columns
    cols = eval_result.get("column_results", []) or []
    scored = [c for c in cols if c.get("similarity") is not None]
    if scored:
        best = max(scored, key=lambda c: c["similarity"])
        worst = min(scored, key=lambda c: c["similarity"])
        findings.append({
            "title": "Most faithful column",
            "text": f"Column '{best['column']}' is reproduced best (similarity {_fmt(best['similarity'])}).",
            "kind": "positive",
        })
        findings.append({
            "title": "Least faithful column",
            "text": f"Column '{worst['column']}' shows the largest difference (similarity {_fmt(worst['similarity'])}). "
                    "Check its distribution chart below to see where the synthetic data deviates.",
            "kind": "warning" if worst["similarity"] < 0.7 else "neutral",
        })

    # Numeric mean shifts
    for c in cols:
        if c.get("type") != "numerical" or not c.get("stats"):
            continue
        mean_pair = c["stats"].get("mean") or {}
        r, s = mean_pair.get("real"), mean_pair.get("synthetic")
        if r is None or s is None or r == 0:
            continue
        shift = abs(s - r) / max(abs(r), 1e-9)
        if shift > 0.15:
            direction = "higher" if s > r else "lower"
            findings.append({
                "title": f"Mean shift in '{c['column']}'",
                "text": f"The synthetic mean of '{c['column']}' is {direction} than the real mean "
                        f"({_fmt(s)} vs {_fmt(r)}, a {shift:.0%} relative shift).",
                "kind": "warning",
            })

    # Correlation structure
    corr = eval_result.get("correlation_comparison") or {}
    mad = corr.get("mean_abs_difference")
    if mad is not None:
        if mad <= 0.1:
            kind = "positive"
            text = (f"Relationships between columns are well preserved: the average difference between real and "
                    f"synthetic associations is only {_fmt(mad)} (0 = identical structure).")
        elif mad <= 0.25:
            kind = "neutral"
            text = (f"Column relationships are moderately preserved (average association difference {_fmt(mad)}). "
                    "Some pairwise relationships are stronger or weaker than in the real data.")
        else:
            kind = "warning"
            text = (f"Column relationships differ noticeably (average association difference {_fmt(mad)}). "
                    "The synthetic data captures individual columns better than the structure between them.")
        findings.append({"title": "Column relationships", "text": text, "kind": kind})
        for d in (corr.get("largest_diffs") or [])[:2]:
            findings.append({
                "title": f"Changed relationship: {d['pair'][0]} ↔ {d['pair'][1]}",
                "text": (f"The association between '{d['pair'][0]}' and '{d['pair'][1]}' changed from "
                         f"{_fmt(d['real'])} in the real data to {_fmt(d['synthetic'])} in the synthetic data."),
                "kind": "warning" if abs(d["difference"]) > 0.25 else "neutral",
            })

    # Target comparison
    tgt = eval_result.get("target_comparison") or {}
    if tgt.get("kind") == "classification" and tgt.get("similarity") is not None:
        props = tgt.get("class_proportions") or []
        if props:
            p0 = props[0]
            diff = abs(p0["real_share"] - p0["synthetic_share"])
            findings.append({
                "title": "Target balance",
                "text": (f"Class shares of '{tgt['target']}' are preserved within {diff:.1%} "
                         f"(e.g. '{p0['category']}': {_fmt(p0['real_share'])} real vs {_fmt(p0['synthetic_share'])} synthetic)."),
                "kind": "positive" if diff < 0.05 else "warning",
            })
    elif tgt.get("kind") == "regression" and tgt.get("similarity") is not None:
        stats_pair = (tgt.get("stats") or {}).get("mean") or {}
        findings.append({
            "title": "Target distribution",
            "text": (f"The synthetic target's mean is {_fmt(stats_pair.get('synthetic'))} vs {_fmt(stats_pair.get('real'))} "
                     f"in the real data (KS similarity {_fmt(tgt.get('similarity'))})."),
            "kind": "positive" if (tgt.get("similarity") or 0) >= 0.85 else "neutral",
        })

    return findings


def explain_ml_utility(ml_result: Dict[str, Any]) -> List[Dict[str, str]]:
    """
    Turn the two-experiment ML results into plain-language findings.
    """
    findings: List[Dict[str, str]] = []
    if not ml_result:
        return findings

    a, b = ml_result.get("experiment_a", {}).get("metrics", {}), ml_result.get("experiment_b", {}).get("metrics", {})
    retention = ml_result.get("retention", {}) or {}
    task = ml_result.get("task")

    if task == "classification":
        primary = "f1"
        label = "F1 score"
        findings.append({
            "title": "Baseline vs synthetic-trained model",
            "text": (f"A model trained on the real data reached {label} {_fmt(a.get(primary))} on the real test set. "
                     f"The same model trained on synthetic data reached {_fmt(b.get(primary))}."),
            "kind": "neutral",
        })
    else:
        primary = "r2"
        label = "R²"
        findings.append({
            "title": "Baseline vs synthetic-trained model",
            "text": (f"A model trained on the real data reached {label} {_fmt(a.get(primary))} on the real test set. "
                     f"The same model trained on synthetic data reached {_fmt(b.get(primary))}."),
            "kind": "neutral",
        })

    r = retention.get(primary)
    if r is not None:
        if r >= 0.9:
            kind, verdict = "positive", "keeps nearly all of the predictive signal"
        elif r >= 0.7:
            kind, verdict = "neutral", "keeps most of the predictive signal"
        else:
            kind, verdict = "warning", "loses a substantial part of the predictive signal"
        findings.append({
            "title": "ML utility retention",
            "text": f"The synthetic-trained model retains {r:.0%} of the baseline {label} — it {verdict}.",
            "kind": kind,
        })

    # Recall drop for classification is pedagogically interesting
    rr = retention.get("recall")
    if task == "classification" and rr is not None and rr < 0.8:
        findings.append({
            "title": "Recall dropped on synthetic data",
            "text": (f"Recall fell to {rr:.0%} of the real-data baseline. The synthetic-trained model misses more "
                     "positive cases on real data — important if missing positives is costly in your application."),
            "kind": "warning",
        })

    findings.append({
        "title": "How to read this experiment",
        "text": ("Both models were tested on the SAME real hold-out rows. The only difference is the training data "
                 "(real vs synthetic). This measures ML usefulness, not privacy: synthetic data is not automatically "
                 "private, anonymous or unbiased."),
        "kind": "neutral",
    })
    return findings


def explain_generation(approach: str, reason: str, warnings: List[str]) -> List[Dict[str, str]]:
    """Explain the generation step itself (synthesizer choice + validation warnings)."""
    out = [{
        "title": f"Generation approach: {approach}",
        "text": reason,
        "kind": "neutral",
    }]
    for w in warnings or []:
        out.append({"title": "Generation warning", "text": w, "kind": "warning"})
    return out
